using System;
using System.IO;
using System.Runtime.InteropServices;
using System.Text;

namespace ShaderCompiler;

public static class Program
{
    private const uint D3DCOMPILE_OPTIMIZATION_LEVEL3 = 0x8000;
    private const uint D3DCOMPILE_ENABLE_STRICTNESS = 0x800;

    [DllImport("d3dcompiler_47.dll", CallingConvention = CallingConvention.Winapi)]
    private static extern int D3DCompile(
        byte[] srcData,
        IntPtr srcDataLen,
        string srcName,
        IntPtr defines,
        IntPtr include,
        string entryPoint,
        string target,
        uint flags1,
        uint flags2,
        out IntPtr code,
        out IntPtr errorMsgs);

    [ComImport, Guid("8BA5FB08-5195-40e2-AC58-0D989C3A0102"), InterfaceType(ComInterfaceType.InterfaceIsIUnknown)]
    private interface ID3DBlob
    {
        [PreserveSig] IntPtr GetBufferPointer();
        [PreserveSig] IntPtr GetBufferSize();
    }

    public static int Main(string[] args)
    {
        if (args.Length == 3 && args[0] == "--glass-header")
            return CompileGlassHeader(args[1], args[2]);

        var positionalArgs = Array.FindAll(args, a => !a.StartsWith('-'));
        string hlslPath = positionalArgs.Length > 0 ? positionalArgs[0] : "Shaders/LiquidGlassRefraction.hlsl";
        string psPath = positionalArgs.Length > 1 ? positionalArgs[1] : "Shaders/LiquidGlassRefraction.ps";

        if (!File.Exists(hlslPath))
        {
            // If executed from Tools/ShaderCompiler, check repo root
            string candidate = Path.Combine(Directory.GetCurrentDirectory(), "..", "..", hlslPath);
            if (File.Exists(candidate))
            {
                hlslPath = Path.GetFullPath(candidate);
                psPath = Path.GetFullPath(Path.Combine(Directory.GetCurrentDirectory(), "..", "..", psPath));
            }
        }

        if (!File.Exists(hlslPath))
        {
            Console.Error.WriteLine($"[ShaderCompiler] Source HLSL file not found: {hlslPath}");
            return 1;
        }

        byte[] src = File.ReadAllBytes(hlslPath);
        int hr = D3DCompile(src, (IntPtr)src.Length, Path.GetFileName(hlslPath), IntPtr.Zero, IntPtr.Zero, "main", "ps_3_0", D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, out IntPtr codePtr, out IntPtr errPtr);
        byte[] bytes;
        try
        {
            if (hr != 0)
            {
                if (errPtr != IntPtr.Zero)
                {
                    var blob = (ID3DBlob)Marshal.GetObjectForIUnknown(errPtr);
                    byte[] err = new byte[blob.GetBufferSize().ToInt32()];
                    Marshal.Copy(blob.GetBufferPointer(), err, 0, err.Length);
                    Console.Error.WriteLine(Encoding.ASCII.GetString(err));
                }
                return hr;
            }

            var codeBlob = (ID3DBlob)Marshal.GetObjectForIUnknown(codePtr);
            bytes = new byte[codeBlob.GetBufferSize().ToInt32()];
            Marshal.Copy(codeBlob.GetBufferPointer(), bytes, 0, bytes.Length);
        }
        finally
        {
            if (codePtr != IntPtr.Zero) Marshal.Release(codePtr);
            if (errPtr != IntPtr.Zero) Marshal.Release(errPtr);
        }

        string? outDir = Path.GetDirectoryName(psPath);
        if (!string.IsNullOrEmpty(outDir) && !Directory.Exists(outDir))
        {
            Directory.CreateDirectory(outDir);
        }

        File.WriteAllBytes(psPath, bytes);
        Console.WriteLine($"[ShaderCompiler] Successfully compiled '{hlslPath}' -> '{psPath}' ({bytes.Length} bytes)");
        return 0;
    }

    private static int CompileGlassHeader(string sourcePath, string headerPath)
    {
        byte[] source = File.ReadAllBytes(sourcePath);
        (string Entry, string Profile, string Symbol)[] shaders =
        [
            ("fullscreenVs", "vs_4_0", "kGlassGpuFullscreenVs"),
            ("cropPs", "ps_4_0", "kGlassGpuCropPs"),
            ("downPs", "ps_4_0", "kGlassGpuDownPs"),
            ("upPs", "ps_4_0", "kGlassGpuUpPs"),
            ("resolvePs", "ps_4_0", "kGlassGpuResolvePs"),
            ("copyPs", "ps_4_0", "kGlassGpuCopyPs"),
            ("refractPs", "ps_4_0", "kGlassGpuRefractPs")
        ];
        var header = new StringBuilder("// Generated by scripts/Generate-GlassShaders.ps1. Do not edit.\n#pragma once\n");
        int totalBytes = 0;
        foreach (var shader in shaders)
        {
            int hr = D3DCompile(source, (IntPtr)source.Length, "GlassGpu", IntPtr.Zero, IntPtr.Zero,
                shader.Entry, shader.Profile, D3DCOMPILE_OPTIMIZATION_LEVEL3 | D3DCOMPILE_ENABLE_STRICTNESS,
                0, out IntPtr code, out IntPtr errors);
            try
            {
                if (hr < 0)
                {
                    if (errors != IntPtr.Zero) Console.Error.WriteLine(Encoding.UTF8.GetString(ReadBlob(errors)));
                    return 1;
                }
                byte[] bytecode = ReadBlob(code);
                totalBytes += bytecode.Length;
                header.Append("inline constexpr unsigned char ").Append(shader.Symbol).Append("[] = {\n");
                for (int i = 0; i < bytecode.Length; i++)
                {
                    if (i % 16 == 0) header.Append("    ");
                    header.Append("0x").Append(bytecode[i].ToString("X2")).Append(',');
                    header.Append(i % 16 == 15 || i == bytecode.Length - 1 ? '\n' : ' ');
                }
                header.Append("};\n");
            }
            finally
            {
                if (code != IntPtr.Zero) Marshal.Release(code);
                if (errors != IntPtr.Zero) Marshal.Release(errors);
            }
        }

        string destination = Path.GetFullPath(headerPath);
        Directory.CreateDirectory(Path.GetDirectoryName(destination)!);
        string temporary = destination + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            File.WriteAllText(temporary, header.ToString(), new UTF8Encoding(false));
            File.Move(temporary, destination, overwrite: true);
        }
        finally { if (File.Exists(temporary)) File.Delete(temporary); }
        Console.WriteLine($"[ShaderCompiler] Compiled {shaders.Length} glass shaders ({totalBytes} bytes) -> '{destination}'");
        return 0;
    }

    private static byte[] ReadBlob(IntPtr pointer)
    {
        var blob = (ID3DBlob)Marshal.GetObjectForIUnknown(pointer);
        try
        {
            var bytes = new byte[checked((int)blob.GetBufferSize())];
            Marshal.Copy(blob.GetBufferPointer(), bytes, 0, bytes.Length);
            return bytes;
        }
        finally { Marshal.ReleaseComObject(blob); }
    }
}
