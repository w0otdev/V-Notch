    public void SetMode(string priorityString)
    {
        string[] newPriority;
        if (string.IsNullOrWhiteSpace(priorityString))
        {
            newPriority = new[] { PriorityNative, PriorityEnglish, PriorityAuto };
        }
        else
        {
            newPriority = priorityString.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
            if (newPriority.Length == 0)
                newPriority = new[] { PriorityNative, PriorityEnglish, PriorityAuto };
        }

        if (!_subtitlePriority.AsSpan().SequenceEqual(newPriority.AsSpan()))
        {
            _subtitlePriority = newPriority;
            Reset();
        }
    }

    public void SetIgnoreAutoGenerated(bool ignore)
    {
        if (_ignoreAutoGenerated != ignore)
        {
            _ignoreAutoGenerated = ignore;
            Reset();
        }
    }

    public void SetNativeLangHint(string? langCode)
    {
        string newHint = string.IsNullOrWhiteSpace(langCode)
            ? ""
