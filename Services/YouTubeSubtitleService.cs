/// <summary>
/// Fetches synced closed-caption (subtitle) tracks for YouTube videos using
/// YouTube's Innertube API (Android client, following youtube-transcript-api architecture)
/// with fallback to YoutubeExplode closed caption manifest.
/// Converts subtitles into <see cref="LyricLine"/> objects for synchronized display.
/// </summary>
internal sealed class YouTubeSubtitleService : IDisposable
{
    private string[] _subtitlePriority = { "native", "english", "auto" };
    private bool _ignoreAutoGenerated = false;
    /// <summary>Hint for the video's native language when no auto-generated track is available.
    /// Typically the system UI language (e.g. "vi") set by the caller.
    /// </summary>
    private string _nativeLangHint = System.Globalization.CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;

    private static readonly HttpClient _httpClient = new()
    {
        Timeout = TimeSpan.FromSeconds(8)
    };

    private static string _innertubeApiKey = "AIzaSyAO_FJ2SlqU8Q4STEHLGCilw_Y9_11qcW8";
    private readonly YoutubeClient _youtube = new();

    private CancellationTokenSource? _cts;
    private string _lastFetchKey = "";
    private List<LyricLine>? _lastFetchedSubtitles;
    private int _fetchGeneration;

    public void SetMode(string priorityString)
    {
        string[] newPriority;
        if (string.IsNullOrWhiteSpace(priorityString))
        {
            newPriority = new[] { "native", "english", "auto" };
        }
        else
        {
            newPriority = priorityString.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
            if (newPriority.Length == 0)
                newPriority = new[] { "native", "english", "auto" };
        }

        if (!_subtitlePriority.SequenceEqual(newPriority))
        {
            _subtitlePriority = newPriority;
            Reset();
        }
    }

    public void SetIgnoreAutoGenerated(bool ignore)
    {
        if (_ignoreAutoGenerated != ignore)
        {
            _ignoreAutoGenerated = ignore;
            Reset();
        }
    }

    /// <summary>Override the native language hint. Pass the two-letter ISO code (e.g. "vi", "ko").
    /// Defaults to the system UI culture language.
    /// </summary>
    public void SetNativeLangHint(string? langCode)
    {
        string newHint = string.IsNullOrWhiteSpace(langCode)
            ? System.Globalization.CultureInfo.CurrentUICulture.TwoLetterISOLanguageName
            : langCode.Trim().ToLowerInvariant();

        if (!string.Equals(_nativeLangHint, newHint, StringComparison.OrdinalIgnoreCase))
        {
            _nativeLangHint = newHint;
            Reset();
        }
    }

    public async Task<List<LyricLine>?> FetchSubtitlesAsync(string videoId, bool force = false)
    {
        if (string.IsNullOrWhiteSpace(videoId)) return null;

        if (!force && videoId == _lastFetchKey && _lastFetchedSubtitles != null && _lastFetchedSubtitles.Count > 0)
        {
            return _lastFetchedSubtitles;
        }

        _cts?.Cancel();
        _cts?.Dispose();
        _cts = new CancellationTokenSource();
        var token = _cts.Token;

        int myGeneration = ++_fetchGeneration;
        _lastFetchKey = videoId;

        try
        {
            RuntimeLog.Log("YT-SUBS", $"Fetching captions for videoId={videoId}");

            // 1. Primary: Direct Innertube Android player API (fast, unthrottled, no poToken required)
            var innertubeLines = await FetchViaInnertubeAsync(videoId, token);
            if (innertubeLines != null && innertubeLines.Count > 0)
            {
                _lastFetchedSubtitles = innertubeLines;
                return innertubeLines;
            }

            // 2. Secondary fallback: YoutubeExplode ClosedCaptions manifest (without calling GetVideoAsync)
            RuntimeLog.Log("YT-SUBS", $"Innertube had no lines, trying ClosedCaptions manifest for {videoId}");
            var manifest = await _youtube.Videos.ClosedCaptions.GetManifestAsync(videoId, token);
            if (manifest.Tracks.Count > 0)
            {
                var trackInfo = SelectTrackFromManifest(manifest);
                if (trackInfo != null)
                {
                    var track = await _youtube.Videos.ClosedCaptions.GetAsync(trackInfo, token);
                    var lines = new List<LyricLine>(track.Captions.Count);
                    foreach (var caption in track.Captions)
                    {
                        string text = caption.Text?.Trim() ?? "";
                        if (text.Length == 0) continue;
                        lines.Add(new LyricLine(caption.Offset, text));
                    }
                    lines.Sort((a, b) => a.Time.CompareTo(b.Time));
                    if (lines.Count > 0)
                    {
                        RuntimeLog.Log("YT-SUBS", $"Got {lines.Count} caption lines via YoutubeExplode for {videoId}");
                        _lastFetchedSubtitles = lines;
                        return lines;
                    }
                }
            }

            RuntimeLog.Log("YT-SUBS", $"No usable caption track found for {videoId}");
            return null;
        }
        catch (OperationCanceledException)
        {
            if (_fetchGeneration == myGeneration && _lastFetchKey == videoId)
                _lastFetchKey = "";
            return null;
        }
        catch (Exception ex)
        {
            RuntimeLog.Log("YT-SUBS", $"Error fetching {videoId}: {ex.Message}");
            if (_fetchGeneration == myGeneration && _lastFetchKey == videoId)
                _lastFetchKey = "";
            return null;
        }
    }

    private async Task<List<LyricLine>?> FetchViaInnertubeAsync(string videoId, CancellationToken token)
    {
        try
        {
            var tracks = await GetInnertubeCaptionTracksAsync(videoId, token);
            if (tracks == null || tracks.Count == 0) return null;

            RuntimeLog.Log("YT-SUBS", $"Innertube found {tracks.Count} tracks for {videoId}: [{string.Join(", ", tracks.Select(t => $"{t.LanguageCode}(vss={t.VssId},auto={t.IsAutoGenerated})"))}]");

            var candidates = GetOrderedCandidateTracks(tracks, _subtitlePriority, _nativeLangHint, _ignoreAutoGenerated);
            foreach (var candidate in candidates)
            {
                if (token.IsCancellationRequested) break;
                try
                {
                    using var req = new HttpRequestMessage(HttpMethod.Get, candidate.BaseUrl);
                    req.Headers.TryAddWithoutValidation("User-Agent", "com.google.android.youtube/20.10.38 (Linux; U; Android 14)");
                    using var resp = await _httpClient.SendAsync(req, HttpCompletionOption.ResponseHeadersRead, token);
                    if (!resp.IsSuccessStatusCode) continue;

                    string content = await resp.Content.ReadAsStringAsync(token);
                    if (string.IsNullOrWhiteSpace(content)) continue;

                    List<LyricLine> lines;
                    string trimmed = content.TrimStart();
                    if (trimmed.StartsWith("{"))
                    {
                        lines = ParseJson3(content);
                    }
                    else
                    {
                        lines = ParseXml(content);
                    }

                    // Check if track has actual speech lyrics (not just empty placeholders)
                    int meaningfulCount = lines.Count(l => !IsPlaceholderLyric(l.Text));
                    if (meaningfulCount > 0)
                    {
                        RuntimeLog.Log("YT-SUBS", $"Got {lines.Count} caption lines via Innertube for {videoId} (lang={candidate.LanguageCode}, vssId={candidate.VssId}, auto={candidate.IsAutoGenerated})");
                        return lines;
                    }
                }
                catch (Exception ex)
                {
                    RuntimeLog.Debug("YT-SUBS", () => $"Error downloading track {candidate.VssId} for {videoId}: {ex.Message}");
                }
            }
        }
        catch (Exception ex)
        {
            RuntimeLog.Debug("YT-SUBS", () => $"Innertube error for {videoId}: {ex.Message}");
        }

        return null;
    }

    private async Task<List<YouTubeCaptionTrack>?> GetInnertubeCaptionTracksAsync(string videoId, CancellationToken token)
    {
        var tracks = await QueryInnertubePlayerAsync(videoId, _innertubeApiKey, token);
        if (tracks != null && tracks.Count > 0) return tracks;

        // If first attempt returned nothing or failed, try refreshing API key from watch page
        string? newKey = await RefreshApiKeyAsync(videoId, token);
        if (!string.IsNullOrEmpty(newKey) && newKey != _innertubeApiKey)
        {
            _innertubeApiKey = newKey;
            tracks = await QueryInnertubePlayerAsync(videoId, _innertubeApiKey, token);
        }

        return tracks;
    }

    private static async Task<List<YouTubeCaptionTrack>?> QueryInnertubePlayerAsync(string videoId, string apiKey, CancellationToken token)
    {
        try
        {
            string url = $"https://www.youtube.com/youtubei/v1/player?key={apiKey}";
            string jsonBody = $"{{\"context\":{{\"client\":{{\"clientName\":\"ANDROID\",\"clientVersion\":\"20.10.38\"}}}},\"videoId\":\"{videoId}\"}}";

            using var req = new HttpRequestMessage(HttpMethod.Post, url)
            {
                Content = new StringContent(jsonBody, Encoding.UTF8, "application/json")
            };
            req.Headers.TryAddWithoutValidation("User-Agent", "com.google.android.youtube/20.10.38 (Linux; U; Android 14)");

            using var resp = await _httpClient.SendAsync(req, HttpCompletionOption.ResponseHeadersRead, token);
            if (!resp.IsSuccessStatusCode) return null;

            using var stream = await resp.Content.ReadAsStreamAsync(token);
            using var doc = await JsonDocument.ParseAsync(stream, cancellationToken: token);

            if (!doc.RootElement.TryGetProperty("captions", out var captionsEl) ||
                !captionsEl.TryGetProperty("playerCaptionsTracklistRenderer", out var tracklistEl) ||
                !tracklistEl.TryGetProperty("captionTracks", out var tracksEl) ||
                tracksEl.ValueKind != JsonValueKind.Array)
            {
                return null;
            }

            var list = new List<YouTubeCaptionTrack>();
            foreach (var t in tracksEl.EnumerateArray())
            {
                string baseUrl = t.TryGetProperty("baseUrl", out var b) ? b.GetString() ?? "" : "";
                if (string.IsNullOrEmpty(baseUrl)) continue;
                // Strip &fmt=srv3 to force standard XML response (same as jdepoix/youtube-transcript-api)
                baseUrl = baseUrl.Replace("&fmt=srv3", "", StringComparison.OrdinalIgnoreCase);

                string lang = t.TryGetProperty("languageCode", out var l) ? l.GetString() ?? "" : "";
                string vssId = t.TryGetProperty("vssId", out var v) ? v.GetString() ?? "" : "";
                string kind = t.TryGetProperty("kind", out var k) ? k.GetString() ?? "" : "";
                string name = "";
                if (t.TryGetProperty("name", out var n))
                {
                    if (n.TryGetProperty("simpleText", out var st)) name = st.GetString() ?? "";
                    else if (n.TryGetProperty("runs", out var runs) && runs.GetArrayLength() > 0)
                    {
                        name = runs[0].TryGetProperty("text", out var txt) ? txt.GetString() ?? "" : "";
                    }
                }
                if (string.IsNullOrEmpty(name)) name = lang;

                bool isAuto = string.Equals(kind, "asr", StringComparison.OrdinalIgnoreCase)
                    || vssId.StartsWith("a.", StringComparison.OrdinalIgnoreCase)
                    || vssId.StartsWith("a:", StringComparison.OrdinalIgnoreCase)
                    || vssId.StartsWith("asr", StringComparison.OrdinalIgnoreCase)
                    || vssId.StartsWith("auto", StringComparison.OrdinalIgnoreCase)
                    || vssId.Contains(".a.", StringComparison.OrdinalIgnoreCase)
                    || baseUrl.Contains("kind=asr", StringComparison.OrdinalIgnoreCase)
                    || name.Contains("auto-generated", StringComparison.OrdinalIgnoreCase)
                    || name.Contains("tự động", StringComparison.OrdinalIgnoreCase)
                    || name.Contains("(auto", StringComparison.OrdinalIgnoreCase)
                    || (t.TryGetProperty("isAutoGenerated", out var ag) && ag.ValueKind == JsonValueKind.True)
                    || (t.TryGetProperty("isAsr", out var asr) && asr.ValueKind == JsonValueKind.True);

                list.Add(new YouTubeCaptionTrack(lang, name, vssId, baseUrl, isAuto));
            }

            return list;
        }
        catch
        {
            return null;
        }
    }

    private static async Task<string?> RefreshApiKeyAsync(string videoId, CancellationToken token)
    {
        try
        {
            string watchUrl = $"https://www.youtube.com/watch?v={videoId}";
            using var req = new HttpRequestMessage(HttpMethod.Get, watchUrl);
            req.Headers.TryAddWithoutValidation("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36");
            req.Headers.TryAddWithoutValidation("Accept-Language", "en-US,en;q=0.9");

            using var resp = await _httpClient.SendAsync(req, HttpCompletionOption.ResponseContentRead, token);
            if (!resp.IsSuccessStatusCode) return null;

            string html = await resp.Content.ReadAsStringAsync(token);
            var m = Regex.Match(html, "\"INNERTUBE_API_KEY\":\\s*\"([a-zA-Z0-9_-]+)\"");
            if (m.Success && m.Groups.Count > 1)
            {
                return m.Groups[1].Value;
            }
        }
        catch
        {
        }
        return null;
    }

    private static bool IsPlaceholderLyric(string text)
    {
        if (string.IsNullOrWhiteSpace(text)) return true;
        string lower = text.Trim().ToLowerInvariant();
        return lower is "[music]" or "[âm nhạc]" or "[applause]" or "[tiếng vỗ tay]" or "♪" or "♫" or "\n";
    }

    /// <summary>
    /// Returns caption tracks ordered by the user's subtitle priority rules.
    /// <para>
    /// Global rule (always enforced): manually uploaded tracks beat auto-generated ones
    /// within the same language group and in the ultimate fallback.
    /// </para>
    /// Priority modes (applied in order):
    /// <list type="bullet">
    ///   <item><term>native</term> Manual track in native lang → auto-generated native track</item>
    ///   <item><term>english</term> Manual English → auto-generated English</item>
    ///   <item><term>auto</term> All manual tracks (non-English first) → all auto tracks</item>
    /// </list>
    /// Each track appears at most once. Unmatched tracks are appended at the end (manual-first).
    /// </summary>
    public static List<YouTubeCaptionTrack> GetOrderedCandidateTracks(
        IReadOnlyList<YouTubeCaptionTrack> tracks,
        IReadOnlyList<string> priorities,
        string? nativeLangHint = null,
        bool ignoreAutoGenerated = false)
    {
        var result = new List<YouTubeCaptionTrack>();
        if (tracks == null || tracks.Count == 0) return result;

        // Detect native language BEFORE filtering (auto-generated track is the definitive native language signal)
        var autoNative = tracks.FirstOrDefault(t => t.IsAutoGenerated && (t.VssId.StartsWith("a.", StringComparison.OrdinalIgnoreCase) || t.VssId.StartsWith("a:", StringComparison.OrdinalIgnoreCase)))
                      ?? tracks.FirstOrDefault(t => t.IsAutoGenerated);
        string nativeLang = autoNative?.LanguageCode
                         ?? (!string.IsNullOrEmpty(nativeLangHint) ? nativeLangHint : "");

        var effectiveTracks = ignoreAutoGenerated
            ? tracks.Where(t => !t.IsAutoGenerated).ToList()
            : tracks.ToList();

        if (effectiveTracks.Count == 0) return result;

        void Add(YouTubeCaptionTrack? t)
        {
            if (t != null && (!ignoreAutoGenerated || !t.IsAutoGenerated) && !result.Contains(t))
                result.Add(t);
        }
        void AddRange(IEnumerable<YouTubeCaptionTrack> seq) { foreach (var t in seq) Add(t); }

        foreach (var mode in priorities)
        {
            switch (mode)
            {
                case "native":
                    if (!string.IsNullOrEmpty(nativeLang))
                    {
                        // 1. Manual track in the video's native language
                        AddRange(effectiveTracks.Where(t => !t.IsAutoGenerated && LanguageCodeMatches(t.LanguageCode, nativeLang)));
                        // 2. Auto-generated native track (only if auto-generated tracks are allowed)
                        if (!ignoreAutoGenerated)
                        {
                            Add(autoNative);
                        }
                    }
                    else
                    {
                        // Native lang unknown and no hint: prioritize non-English manual tracks
                        // since "native" priority was explicitly requested before English.
                        AddRange(effectiveTracks.Where(t => !t.IsAutoGenerated && !LanguageCodeMatches(t.LanguageCode, "en")));
                    }
                    break;

                case "english":
                    // 1. Manual English track
                    AddRange(effectiveTracks.Where(t => !t.IsAutoGenerated && LanguageCodeMatches(t.LanguageCode, "en")));
                    // 2. Auto-generated English track (only if auto-generated tracks are allowed)
                    if (!ignoreAutoGenerated)
                    {
                        AddRange(effectiveTracks.Where(t => t.IsAutoGenerated && LanguageCodeMatches(t.LanguageCode, "en")));
                    }
                    break;

                case "auto":
                    // All manual tracks (non-English first so native-language videos are preferred over English)
                    AddRange(effectiveTracks.Where(t => !t.IsAutoGenerated && !LanguageCodeMatches(t.LanguageCode, "en")));
                    AddRange(effectiveTracks.Where(t => !t.IsAutoGenerated));
                    // All auto-generated tracks (only if auto-generated tracks are allowed)
                    if (!ignoreAutoGenerated)
                    {
                        AddRange(effectiveTracks.Where(t => t.IsAutoGenerated));
                    }
                    break;
            }
        }

        // Global rule: manually uploaded tracks always take priority over auto-generated ones.
        // The ultimate fallback also respects this — remaining tracks appended manual-first.
        AddRange(effectiveTracks.Where(t => !t.IsAutoGenerated));
        if (!ignoreAutoGenerated)
        {
            AddRange(effectiveTracks.Where(t => t.IsAutoGenerated));
        }
        return result;
    }


    /// <summary>
    /// Returns the URL of the best caption track given priority rules.
    /// Delegates to <see cref="GetOrderedCandidateTracks"/> for consistent ordering.
    /// </summary>
    public static string? SelectCaptionTrackUrl(
        IReadOnlyList<YouTubeCaptionTrack> tracks,
        IReadOnlyList<string> priorities,
        string? nativeLangHint = null,
        bool ignoreAutoGenerated = false)
    {
        var ordered = GetOrderedCandidateTracks(tracks, priorities, nativeLangHint, ignoreAutoGenerated);
        return ordered.Count > 0 ? ordered[0].BaseUrl : null;
    }

    // YoutubeExplode manifest fallback — same priority rules applied to ClosedCaptionTrackInfo
    private ClosedCaptionTrackInfo? SelectTrackFromManifest(ClosedCaptionManifest manifest)
    {
        var allTracks = manifest.Tracks.ToList();
        if (allTracks.Count == 0) return null;

        var autoNative = allTracks.FirstOrDefault(t => t.IsAutoGenerated);
        string nativeLang = autoNative?.Language.Code
                         ?? (!string.IsNullOrEmpty(_nativeLangHint) ? _nativeLangHint : "");

        var trackList = _ignoreAutoGenerated
            ? allTracks.Where(t => !t.IsAutoGenerated).ToList()
            : allTracks;

        if (trackList.Count == 0) return null;

        foreach (var mode in _subtitlePriority)
        {
            switch (mode)
            {
                case "native":
                    if (!string.IsNullOrEmpty(nativeLang))
                    {
                        var manualNative = trackList.FirstOrDefault(t => !t.IsAutoGenerated && LanguageCodeMatches(t.Language.Code, nativeLang));
                        if (manualNative != null) return manualNative;
                        if (!_ignoreAutoGenerated && autoNative != null) return autoNative;
                    }
                    var nonEn = trackList.FirstOrDefault(t => !t.IsAutoGenerated && !LanguageCodeMatches(t.Language.Code, "en"));
                    if (nonEn != null) return nonEn;
                    break;

                case "english":
                    var manualEn = trackList.FirstOrDefault(t => !t.IsAutoGenerated && LanguageCodeMatches(t.Language.Code, "en"));
                    if (manualEn != null) return manualEn;
                    if (!_ignoreAutoGenerated)
                    {
                        var autoEn = trackList.FirstOrDefault(t => t.IsAutoGenerated && LanguageCodeMatches(t.Language.Code, "en"));
                        if (autoEn != null) return autoEn;
                    }
                    break;

                case "auto":
                    var anyManual = trackList.FirstOrDefault(t => !t.IsAutoGenerated);
                    if (anyManual != null) return anyManual;
                    if (!_ignoreAutoGenerated)
                        return trackList.FirstOrDefault();
                    break;
            }
        }

        return trackList.FirstOrDefault(t => !_ignoreAutoGenerated || !t.IsAutoGenerated);
    }


    private static bool LanguageCodeMatches(string code1, string code2)
    {
        if (string.Equals(code1, code2, StringComparison.OrdinalIgnoreCase)) return true;
        string base1 = code1.Contains('-') ? code1.Split('-')[0] : code1;
        string base2 = code2.Contains('-') ? code2.Split('-')[0] : code2;
        return string.Equals(base1, base2, StringComparison.OrdinalIgnoreCase);
    }

    public static List<LyricLine> ParseJson3(string json)
    {
        var result = new List<LyricLine>();
        try
        {
            using var doc = System.Text.Json.JsonDocument.Parse(json);
            if (doc.RootElement.TryGetProperty("events", out var events))
            {
                foreach (var ev in events.EnumerateArray())
                {
                    if (ev.TryGetProperty("segs", out var segs) && ev.TryGetProperty("tStartMs", out var tStart))
                    {
                        var sb = new System.Text.StringBuilder();
                        foreach (var s in segs.EnumerateArray())
                        {
                            if (s.TryGetProperty("utf8", out var u))
                            {
                                sb.Append(u.GetString());
                            }
                        }
                        string text = sb.ToString().Trim();
                        if (!string.IsNullOrWhiteSpace(text) && text != "\n")
                        {
                            long ms = tStart.GetInt64();
                            result.Add(new LyricLine(TimeSpan.FromMilliseconds(ms), text));
                        }
                    }
                }
            }
            result.Sort((a, b) => a.Time.CompareTo(b.Time));
        }
        catch (Exception ex)
        {
            RuntimeLog.Debug("YT-SUBS", () => $"ParseJson3 error: {ex.Message}");
        }
        return result;
    }

    public static List<LyricLine> ParseXml(string xml)
    {
        var result = new List<LyricLine>();
        try
        {
            var doc = System.Xml.Linq.XDocument.Parse(xml);
            var pElements = doc.Descendants("p").Concat(doc.Descendants("text"));
            foreach (var p in pElements)
            {
                string text = System.Net.WebUtility.HtmlDecode(System.Text.RegularExpressions.Regex.Replace(p.Value, @"<[^>]*>", "")).Trim();
                if (string.IsNullOrWhiteSpace(text)) continue;

                var tAttr = p.Attribute("t");
                var startAttr = p.Attribute("start");

                TimeSpan timestamp;
                if (tAttr != null && long.TryParse(tAttr.Value, out long ms))
                {
                    timestamp = TimeSpan.FromMilliseconds(ms);
                }
                else if (startAttr != null && double.TryParse(startAttr.Value, System.Globalization.NumberStyles.Any, System.Globalization.CultureInfo.InvariantCulture, out double sec))
                {
                    timestamp = TimeSpan.FromSeconds(sec);
                }
                else
                {
                    continue;
                }

                result.Add(new LyricLine(timestamp, text));
            }
            result.Sort((a, b) => a.Time.CompareTo(b.Time));
        }
        catch (Exception ex)
        {
            RuntimeLog.Debug("YT-SUBS", () => $"ParseXml error: {ex.Message}");
        }
        return result;
    }

    public void Reset()
    {
        _lastFetchKey = "";
        _lastFetchedSubtitles = null;
        _fetchGeneration++;
        _cts?.Cancel();
    }

    public void Dispose()
    {
        _cts?.Cancel();
        _cts?.Dispose();
    }
}

