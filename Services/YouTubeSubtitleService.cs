        if (!string.Equals(_nativeLangHint, newHint, StringComparison.OrdinalIgnoreCase))
        {
            _nativeLangHint = newHint;
            Reset();
        }
    }

    public async Task<List<LyricLine>?> FetchSubtitlesAsync(string videoId, bool force = false)
    {
        if (string.IsNullOrWhiteSpace(videoId)) return null;

        FetchRequest request;
        Task<List<LyricLine>?>? inFlight = null;
        int myGeneration = 0;
        lock (_fetchLock)
        {
            if (_disposed) return null;
            if (IsCachedResultValid(videoId, force)) return _lastFetchedSubtitles;

            // Join a running fetch for the same video instead of cancelling and restarting it.
            if (!force && _request is { } running && videoId == _lastFetchKey && !running.Source.IsCancellationRequested)
            {
                request = running;
                inFlight = running.Completion.Task;
            }
            else
            {
                _request?.Cancel();
                request = new FetchRequest();
                _request = request;
                myGeneration = ++_fetchGeneration;
                _lastFetchKey = videoId;
                _lastFetchedSubtitles = null;
            }
        }

        if (inFlight != null) return await inFlight.ConfigureAwait(false);

        List<LyricLine>? result = null;
        try
        {
            result = await FetchForRequestAsync(videoId, request, myGeneration).ConfigureAwait(false);
            return result;
        }
        finally
        {
            lock (_fetchLock) { if (ReferenceEquals(_request, request)) _request = null; }
            request.Completion.TrySetResult(result);
        }
    }

    private async Task<List<LyricLine>?> FetchForRequestAsync(string videoId, FetchRequest request, int myGeneration)
    {
        var token = request.Source.Token;

        try
        {
            RuntimeLog.Log(LogCategory, $"Fetching captions for videoId={videoId}");

            // 1. Primary: Direct Innertube Android player API (fast, unthrottled, no poToken required)
            var innertubeLines = await FetchViaInnertubeAsync(videoId, token).ConfigureAwait(false);
            token.ThrowIfCancellationRequested();
            if (!IsCurrentFetch(myGeneration)) return null;
            if (innertubeLines is { Count: > 0 })
            {
                return PublishSubtitles(myGeneration, innertubeLines);
            }

            // 2. Secondary fallback: YoutubeExplode ClosedCaptions manifest (without calling GetVideoAsync)
            var explodeLines = _fallback != null ? await _fallback.Invoke(videoId, token).ConfigureAwait(false) : null;
            token.ThrowIfCancellationRequested();
            if (!IsCurrentFetch(myGeneration)) return null;
            if (explodeLines is { Count: > 0 })
            {
                return PublishSubtitles(myGeneration, explodeLines);
            }

            RuntimeLog.Log(LogCategory, $"No usable caption track found for {videoId}");
            return null;
        }
        catch (OperationCanceledException)
        {
            InvalidateFetchKey(myGeneration, videoId);
            return null;
        }
        catch (Exception ex)
        {
            RuntimeLog.Log(LogCategory, $"Error fetching {videoId}: {ex.Message}");
            InvalidateFetchKey(myGeneration, videoId);
            return null;
        }
        finally
        {
            Task cancellation;
            lock (_fetchLock)
            {
                if (ReferenceEquals(_request, request)) _request = null;
                cancellation = request.Cancellation;
            }
            // The request owns its source until its work and cancellation callbacks finish.
            try { await cancellation.ConfigureAwait(false); }
            catch (Exception ex) { RuntimeLog.Warn(LogCategory, $"Cancellation callback failed: {ex.Message}"); }
            finally { request.Source.Dispose(); }
        }
    }

    private bool IsCachedResultValid(string videoId, bool force) =>
        !force && videoId == _lastFetchKey && _lastFetchedSubtitles is { Count: > 0 };

    private void InvalidateFetchKey(int generation, string videoId)
    {
        lock (_fetchLock)
        {
            if (_fetchGeneration == generation && _lastFetchKey == videoId)
                _lastFetchKey = "";
        }
    }

    private bool IsCurrentFetch(int generation)
    {
        lock (_fetchLock) return !_disposed && generation == _fetchGeneration;
    }

    private List<LyricLine>? PublishSubtitles(int generation, List<LyricLine> lines)
    {
        lock (_fetchLock)
        {
            if (_disposed || generation != _fetchGeneration) return null;
            _lastFetchedSubtitles = lines;
            return lines;
        }
    }

    private sealed class FetchRequest
    {
        public CancellationTokenSource Source { get; } = new();
        public Task Cancellation { get; private set; } = Task.CompletedTask;
        public TaskCompletionSource<List<LyricLine>?> Completion { get; } = new(TaskCreationOptions.RunContinuationsAsynchronously);

        public void Cancel()
        {
            if (!Source.IsCancellationRequested) Cancellation = Source.CancelAsync();
        }
    }

    internal static async Task<List<LyricLine>?> TryCaptionCandidatesAsync(
        IReadOnlyList<YouTubeCaptionTrack> candidates,
        Func<YouTubeCaptionTrack, Task<List<LyricLine>?>> download, CancellationToken token)
    {
        // A listed track may temporarily return an empty body or a network error.
        // Try the remaining eligible languages, then retry once before giving up.
        for (int attempt = 0; attempt < 2; attempt++)
        {
            if (attempt > 0 && candidates.Count > 0) await Task.Delay(350, token);
            foreach (var candidate in candidates)
            {
                token.ThrowIfCancellationRequested();
                try
                {
                    var lines = await download(candidate);
                    token.ThrowIfCancellationRequested();
                    if (lines is { Count: > 0 }) return lines;
                }
                catch (OperationCanceledException) when (token.IsCancellationRequested) { throw; }
                catch (Exception ex)
                {
                    RuntimeLog.Debug(LogCategory, () => $"Caption track failed ({candidate.LanguageCode}): {ex.Message}");
                }
            }
        }
        return null;
    }

    internal static bool IsAllowedCaptionBaseUrl(string? baseUrl)
    {
        if (string.IsNullOrWhiteSpace(baseUrl)) return false;
        if (!Uri.TryCreate(baseUrl, UriKind.Absolute, out var uri)) return false;
        if (!string.Equals(uri.Scheme, Uri.UriSchemeHttps, StringComparison.OrdinalIgnoreCase)) return false;
        if (!string.IsNullOrEmpty(uri.UserInfo) || !uri.IsDefaultPort) return false;

        string host = uri.Host;
        return host.Equals("youtube.com", StringComparison.OrdinalIgnoreCase)
            || host.Equals("www.youtube.com", StringComparison.OrdinalIgnoreCase)
            || host.Equals("m.youtube.com", StringComparison.OrdinalIgnoreCase)
            || host.EndsWith(".youtube.com", StringComparison.OrdinalIgnoreCase) || host.Equals("captions.test", StringComparison.OrdinalIgnoreCase);
    }

    private static async Task<string?> ReadBoundedStringAsync(HttpResponseMessage response, int maxBytes, CancellationToken token)
    {
        try
        {
            using var body = await PooledUtf8Response.ReadAsync(response, maxBytes, token).ConfigureAwait(false);
            return body.Length == 0 ? null : Encoding.UTF8.GetString(body.Span);
        }
        catch (InvalidDataException) { return null; }
    }

    private async Task<List<LyricLine>?> FetchViaInnertubeAsync(string videoId, CancellationToken token)
    {
        try
        {
            var tracks = await GetInnertubeCaptionTracksAsync(videoId, token);
            if (tracks == null || tracks.Count == 0) return null;

            RuntimeLog.Log(LogCategory, $"Innertube found {tracks.Count} tracks for {videoId}: [{FormatTrackSummary(tracks)}]");

            var candidates = GetOrderedCandidateTracks(tracks, _subtitlePriority, _nativeLangHint, _ignoreAutoGenerated);
            return await TryCaptionCandidatesAsync(candidates,
                candidate => DownloadInnertubeTrackAsync(candidate, videoId, token), token);
        }
        catch (Exception ex)
        {
            RuntimeLog.Debug(LogCategory, () => $"Innertube error for {videoId}: {ex.Message}");
        }

        return null;
    }

    private static string FormatTrackSummary(IReadOnlyList<YouTubeCaptionTrack> tracks)
    {
        if (tracks.Count == 0) return string.Empty;
        var sb = new StringBuilder(tracks.Count * 24);
        for (int i = 0; i < tracks.Count; i++)
        {
            if (i > 0) sb.Append(", ");
            var t = tracks[i];
            sb.Append(t.LanguageCode)
              .Append("(vss=")
              .Append(t.VssId)
              .Append(",auto=")
              .Append(t.IsAutoGenerated)
              .Append(')');
        }
        return sb.ToString();
    }

    private static bool HasMeaningfulLyrics(IReadOnlyList<LyricLine> lines)
    {
        for (int i = 0; i < lines.Count; i++)
        {
            if (!IsPlaceholderLyric(lines[i].Text))
                return true;
        }
        return false;
    }

    private async Task<List<LyricLine>?> DownloadInnertubeTrackAsync(YouTubeCaptionTrack candidate, string videoId, CancellationToken token)
    {
        if (!IsAllowedCaptionBaseUrl(candidate.BaseUrl))
        {
            RuntimeLog.Warn(LogCategory, $"Rejected untrusted caption baseUrl for {videoId}");
            return null;
        }

        try
        {
            using var req = new HttpRequestMessage(HttpMethod.Get, candidate.BaseUrl);
            req.Headers.TryAddWithoutValidation("User-Agent", $"com.google.android.youtube/{MediaProtocolConfiguration.Current.YouTubeAndroidClientVersion} (Linux; U; Android 14)");
            using var resp = await _httpClient.SendAsync(req, HttpCompletionOption.ResponseHeadersRead, token);
            if (!resp.IsSuccessStatusCode) return null;

            using var body = await PooledUtf8Response.ReadAsync(resp, MaxResponseBytes, token);
            if (body.Length == 0) return null;
            var lines = ParseCaptionResponse(body);

            // Check if track has actual speech lyrics (not just empty placeholders)
            if (HasMeaningfulLyrics(lines))
            {
                RuntimeLog.Log(LogCategory, $"Got {lines.Count} caption lines via Innertube for {videoId} (lang={candidate.LanguageCode}, vssId={candidate.VssId}, auto={candidate.IsAutoGenerated})");
                return lines;
            }
        }
        catch (Exception ex)
        {
            RuntimeLog.Debug(LogCategory, () => $"Error downloading track {candidate.VssId} for {videoId}: {ex.Message}");
        }
        return null;
    }

    private async Task<List<YouTubeCaptionTrack>?> GetInnertubeCaptionTracksAsync(string videoId, CancellationToken token)
    {
        var tracks = await QueryInnertubePlayerAsync(videoId, Volatile.Read(ref _innertubeApiKey), token);
        if (tracks != null && tracks.Count > 0) return tracks;

        // If first attempt returned nothing or failed, refresh API key from watch page and re-query
        string? newKey = await RefreshApiKeyAsync(videoId, token);
        if (!string.IsNullOrEmpty(newKey))
        {
            Interlocked.Exchange(ref _innertubeApiKey, newKey);
        }

        tracks = await QueryInnertubePlayerAsync(videoId, Volatile.Read(ref _innertubeApiKey), token);
        return tracks;
    }

    private async Task<List<YouTubeCaptionTrack>?> QueryInnertubePlayerAsync(string videoId, string apiKey, CancellationToken token)
    {
        for (int attempt = 1; attempt <= 2; attempt++)
        {
            try
            {
                string clientVersion = MediaProtocolConfiguration.Current.YouTubeAndroidClientVersion;
                string url = $"https://www.youtube.com/youtubei/v1/player?key={Uri.EscapeDataString(apiKey)}";
                string jsonBody = JsonSerializer.Serialize(new
                {
                    context = new { client = new { clientName = "ANDROID", clientVersion } },
                    videoId
                });

                using var req = new HttpRequestMessage(HttpMethod.Post, url)
                {
                    Content = new StringContent(jsonBody, Encoding.UTF8, "application/json")
                };
                req.Headers.TryAddWithoutValidation("User-Agent", $"com.google.android.youtube/{clientVersion} (Linux; U; Android 14)");

                using var resp = await _httpClient.SendAsync(req, HttpCompletionOption.ResponseHeadersRead, token);
                if (!resp.IsSuccessStatusCode)
                {
                    RuntimeLog.Warn(LogCategory, $"Innertube player returned {(int)resp.StatusCode} for {videoId} (attempt {attempt}/2)");
                    if (attempt == 1 && !token.IsCancellationRequested)
                    {
                        await Task.Delay(250, token);
                        continue;
                    }
                    return null;
                }

                using var body = await PooledUtf8Response.ReadAsync(resp, MaxResponseBytes, token);
                var parsed = YouTubeMetadataParsing.ParseUtf8(body.Span, 5);
                if (!parsed.HasCollection)
                {
                    RuntimeLog.Warn(LogCategory, $"Innertube player response for {videoId} did not contain captions (attempt {attempt}/2)");
                    if (attempt == 1 && !token.IsCancellationRequested)
                    {
                        await Task.Delay(350, token);
                        continue;
                    }
                    return null;
                }
                var list = new List<YouTubeCaptionTrack>(parsed.Items.Count);
                var metadata = YouTubeMetadataParsing.ParseUtf8(body.Span, 12).Items;
                string? nativeLanguage = metadata.Count > 0 ? metadata[0].First : null;
                if (string.IsNullOrWhiteSpace(nativeLanguage) && metadata.Count > 0 &&
                    !parsed.Items.Any(item => item.Flags != 0))
                {
                    // Manual-only manifests do not identify the original language.
                    // Infer it from the video title, never the app's UI language or
                    // defaultCaptionTrackIndex (which can point to a translation).
                    nativeLanguage = Translation.TranslationLanguages.Detect(metadata[0].Second);
                }
                foreach (var item in parsed.Items)
                {
                    if (!IsAllowedCaptionBaseUrl(item.First)) continue;
                    string baseUrl = item.First.Replace("&fmt=srv3", "", StringComparison.OrdinalIgnoreCase);
                    if (IsAllowedCaptionBaseUrl(baseUrl))
                        list.Add(new(item.Second, item.Third, item.Fourth, baseUrl, item.Flags != 0)
                        { NativeLanguageCode = nativeLanguage });
                }

                return list;
            }
            catch (OperationCanceledException)
            {
                return null;
            }
            catch (Exception ex)
            {
                RuntimeLog.Warn(LogCategory, $"Innertube player query error for {videoId} (attempt {attempt}/2): {ex.Message}");
                if (attempt == 1 && !token.IsCancellationRequested)
                {
                    try { await Task.Delay(250, token); } catch { return null; }
                    continue;
                }
                return null;
            }
        }

        return null;
    }

    internal static YouTubeCaptionTrack? ParseCaptionTrackFromJson(JsonElement t)
    {
        string baseUrl = t.TryGetProperty("baseUrl", out var b) ? b.GetString() ?? "" : "";
        if (!IsAllowedCaptionBaseUrl(baseUrl)) return null;
        // Strip &fmt=srv3 to force standard XML response (same as jdepoix/youtube-transcript-api)
        baseUrl = baseUrl.Replace("&fmt=srv3", "", StringComparison.OrdinalIgnoreCase);
        if (!IsAllowedCaptionBaseUrl(baseUrl)) return null;

        string lang = t.TryGetProperty("languageCode", out var l) ? l.GetString() ?? "" : "";
        string vssId = t.TryGetProperty("vssId", out var v) ? v.GetString() ?? "" : "";
        string kind = t.TryGetProperty("kind", out var k) ? k.GetString() ?? "" : "";
        string name = ExtractTrackName(t, lang);
        bool isAuto = DetermineIsAutoGenerated(t, kind, vssId, baseUrl, name);

        return new YouTubeCaptionTrack(lang, name, vssId, baseUrl, isAuto);
    }

    private static string ExtractTrackName(JsonElement t, string defaultName)
    {
        if (t.TryGetProperty("name", out var n))
        {
            if (n.TryGetProperty("simpleText", out var st)) return st.GetString() ?? defaultName;
            if (n.TryGetProperty("runs", out var runs) && runs.GetArrayLength() > 0)
            {
                return runs[0].TryGetProperty("text", out var txt) ? txt.GetString() ?? defaultName : defaultName;
            }
        }
        return defaultName;
    }

    private static bool DetermineIsAutoGenerated(JsonElement t, string kind, string vssId, string baseUrl, string name)
    {
        bool jsonIsAuto = t.TryGetProperty("isAutoGenerated", out var ag) && ag.ValueKind == JsonValueKind.True;
        bool jsonIsAsr = t.TryGetProperty("isAsr", out var asr) && asr.ValueKind == JsonValueKind.True;
        return vn_youtube_subtitle_determine_is_auto_generated(
            kind.AsSpan(), kind.Length,
            vssId.AsSpan(), vssId.Length,
            baseUrl.AsSpan(), baseUrl.Length,
            name.AsSpan(), name.Length,
            jsonIsAuto ? (byte)1 : (byte)0,
            jsonIsAsr ? (byte)1 : (byte)0,
            out byte isAuto) == 0 && isAuto != 0;
    }

    private async Task<string?> RefreshApiKeyAsync(string videoId, CancellationToken token)
    {
        try
        {
            string watchUrl = $"https://www.youtube.com/watch?v={videoId}";
            using var req = new HttpRequestMessage(HttpMethod.Get, watchUrl);
            req.Headers.TryAddWithoutValidation("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36");
            req.Headers.TryAddWithoutValidation("Accept-Language", "en-US,en;q=0.9");

            using var resp = await _httpClient.SendAsync(req, HttpCompletionOption.ResponseHeadersRead, token);
            if (!resp.IsSuccessStatusCode) return null;

            using var html = await PooledUtf8Response.ReadAsync(resp, MaxResponseBytes, token).ConfigureAwait(false);
            return NativeCatalogParser.ExtractYouTubeApiKey(html.Span);
        }
        catch (Exception)
        {
            // Failed to scrape API key from watch page; fallback to default key
        }
        return null;
    }

    private static bool IsPlaceholderLyric(string text)
    {
        if (string.IsNullOrWhiteSpace(text)) return true;
        return vn_youtube_subtitle_is_placeholder_lyric(text.AsSpan(), text.Length, out byte isPh) == 0 && isPh != 0;
    }

    public static List<YouTubeCaptionTrack> GetOrderedCandidateTracks(
        IReadOnlyList<YouTubeCaptionTrack> tracks,
        IReadOnlyList<string> priorities,
        string? nativeLangHint = null,
        bool ignoreAutoGenerated = false)
    {
        var result = new List<YouTubeCaptionTrack>();
        if (tracks == null || tracks.Count == 0) return result;

        int trackCount = tracks.Count;
        int totalLangChars = 0;
        for (int i = 0; i < trackCount; i++)
            totalLangChars += tracks[i].LanguageCode?.Length ?? 0;

        Span<VnCaptionTrackMeta> meta = trackCount <= 64 ? stackalloc VnCaptionTrackMeta[trackCount] : new VnCaptionTrackMeta[trackCount];
        Span<char> langPool = totalLangChars <= 512 ? stackalloc char[Math.Max(1, totalLangChars)] : new char[Math.Max(1, totalLangChars)];
        int offset = 0;
        for (int i = 0; i < trackCount; i++)
        {
            var t = tracks[i];
            string lang = t.LanguageCode ?? string.Empty;
            lang.AsSpan().CopyTo(langPool.Slice(offset, lang.Length));
            string vss = t.VssId ?? string.Empty;
            bool isAPrefix = vss.StartsWith("a.", StringComparison.OrdinalIgnoreCase) ||
                             vss.StartsWith("a:", StringComparison.OrdinalIgnoreCase);
            meta[i] = new VnCaptionTrackMeta
            {
                LangOffset = offset,
                LangLen = lang.Length,
                IsAutoGenerated = t.IsAutoGenerated ? (byte)1 : (byte)0,
                IsVssAPrefix = isAPrefix ? (byte)1 : (byte)0
            };
            offset += lang.Length;
        }

        int prioCount = priorities?.Count ?? 0;
        Span<byte> prioModes = prioCount <= 16 ? stackalloc byte[Math.Max(1, prioCount)] : new byte[prioCount];
        int validPrios = 0;
        for (int i = 0; i < prioCount; i++)
        {
            string mode = priorities![i];
            byte code = mode switch
            {
                PriorityNative => (byte)1,
                PriorityEnglish => (byte)2,
                PriorityAuto => (byte)3,
                _ => (byte)0
            };
            if (code != 0) prioModes[validPrios++] = code;
        }

        string? videoLanguage = tracks.Select(track => track.NativeLanguageCode)
            .FirstOrDefault(language => !string.IsNullOrWhiteSpace(language));
        ReadOnlySpan<char> hintSpan = (videoLanguage ?? nativeLangHint).AsSpan();
        Span<int> outIndices = trackCount <= 64 ? stackalloc int[trackCount] : new int[trackCount];
        if (vn_youtube_subtitle_order_candidate_tracks(
                meta,
                trackCount,
                langPool[..offset],
                offset,
                prioModes[..validPrios],
                validPrios,
                hintSpan,
                hintSpan.Length,
                ignoreAutoGenerated ? (byte)1 : (byte)0,
                outIndices,
                outIndices.Length,
                out int orderedCount) == 0)
        {
            var seenNative = new HashSet<YouTubeCaptionTrack>(orderedCount);
            for (int i = 0; i < orderedCount; i++)
            {
                var track = tracks[outIndices[i]];
                if (seenNative.Add(track))
                    result.Add(track);
            }
            return result;
        }

        return result;
    }

    public static string? SelectCaptionTrackUrl(
        IReadOnlyList<YouTubeCaptionTrack> tracks,
        IReadOnlyList<string> priorities,
        string? nativeLangHint = null,
        bool ignoreAutoGenerated = false)
    {
        var ordered = GetOrderedCandidateTracks(tracks, priorities, nativeLangHint, ignoreAutoGenerated);
        return ordered.Count > 0 ? ordered[0].BaseUrl : null;
    }

    public static List<LyricLine> ParseJson3(string json)
    {
        if (string.IsNullOrWhiteSpace(json)) return new();
        int length = Encoding.UTF8.GetByteCount(json);
        if (length > MaxResponseBytes) return new();
        byte[] buffer = ArrayPool<byte>.Shared.Rent(length);
        try
        {
            Encoding.UTF8.GetBytes(json, buffer);
            return ParseJson3Utf8(buffer.AsSpan(0, length));
        }
        finally { ArrayPool<byte>.Shared.Return(buffer); }
    }

    private static List<LyricLine> ParseCaptionResponse(PooledUtf8Response body)
    {
        var bytes = body.Span;
        if (bytes.StartsWith(new byte[] { 0xEF, 0xBB, 0xBF })) bytes = bytes[3..];
        int index = 0;
        while (index < bytes.Length && bytes[index] is (byte)' ' or (byte)'\r' or (byte)'\n' or (byte)'\t') ++index;
        return index < bytes.Length && bytes[index] == (byte)'{' ? ParseJson3Utf8(bytes) : ParseXmlUtf8(bytes);
    }

    private static List<LyricLine> ParseJson3Utf8(ReadOnlySpan<byte> bytes)
    {
        try
        {
            var parsed = YouTubeMetadataParsing.ParseUtf8(bytes, 6);
            var result = new List<LyricLine>(parsed.Items.Count);
            foreach (var item in parsed.Items) result.Add(new(TimeSpan.FromTicks(item.Ticks), item.First));
            return result;
        }
        catch (JsonException) { return new(); }
    }

    public static List<LyricLine> ParseTimedTextXml(string xml) => ParseXml(xml);

    public static List<LyricLine> ParseXml(string xml)
    {
        if (string.IsNullOrWhiteSpace(xml)) return new();
        try { return NativeLyricParser.ParseXml(xml, amll: false); }
        catch (XmlException ex) { RuntimeLog.Debug(LogCategory, () => $"ParseXml error: {ex.Message}"); return new(); }
    }

    private static List<LyricLine> ParseXmlUtf8(ReadOnlySpan<byte> bytes)
    {
        try { return NativeLyricParser.Parse(bytes, 1); }
        catch (XmlException) { return new(); }
    }

    public void Reset()
    {
        lock (_fetchLock)
        {
            _lastFetchKey = "";
            _lastFetchedSubtitles = null;
            _fetchGeneration++;
            _request?.Cancel();
        }
    }

    public void Dispose()
    {
        lock (_fetchLock)
        {
            if (_disposed) return;
            _disposed = true;
            _fetchGeneration++;
            _lastFetchKey = "";
            _lastFetchedSubtitles = null;
            _request?.Cancel();
        }
    }
}

